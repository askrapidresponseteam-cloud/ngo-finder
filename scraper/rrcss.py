"""The directory's stylesheet for rapid-response.in.

The page there carries the site's own header, footer and theme tokens
(--sg-*), and mounts the directory inside <div id="ngo-app" class="ngo-rr">.
This writes rr.css: styles.css with every rule scoped to .ngo-rr (so nothing
leaks onto the host page), then web/rr-theme.css (the Rapid Response look:
square corners, hairlines, Archivo headings, mono labels, ink data, one red),
scoped the same way.

    python3 -m scraper.rrcss site/rr.css
"""
import os
import re
import sys

WEB = os.path.join(os.path.dirname(os.path.abspath(__file__)), "web")
SCOPE = ".ngo-rr"


def _split_selectors(sel):
    out, depth, cur = [], 0, ""
    for ch in sel:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    out.append(cur)
    return [s.strip() for s in out if s.strip()]


def _scope_selector(sel):
    m = re.match(r"^(:root|html|body)\b(.*)$", sel)
    if m:
        rest = m.group(2).strip()
        return SCOPE + (" " + rest if rest else "")
    return SCOPE + " " + sel


def _block_end(css, i):
    """Index just past the } that closes the { at css[i]."""
    depth = 0
    for j in range(i, len(css)):
        if css[j] == "{":
            depth += 1
        elif css[j] == "}":
            depth -= 1
            if depth == 0:
                return j + 1
    raise ValueError("unbalanced braces in stylesheet")


def scope(css):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    out, i = [], 0
    while i < len(css):
        b = css.find("{", i)
        if b < 0:
            break
        head = css[i:b].strip()
        end = _block_end(css, b)
        body = css[b + 1:end - 1]
        if head.startswith("@media") or head.startswith("@supports"):
            out.append(head + "{" + scope(body) + "}")
        elif head.startswith("@"):
            out.append(head + "{" + body.strip() + "}")  # keyframes, font-face: as they are
        else:
            sels = []
            for s in _split_selectors(head):
                t = _scope_selector(s)
                if t not in sels:
                    sels.append(t)
            out.append(",".join(sels) + "{" + body.strip() + "}")
        i = end
    return "\n".join(out)


def build():
    with open(os.path.join(WEB, "styles.css"), encoding="utf-8") as fh:
        base = fh.read()
    with open(os.path.join(WEB, "rr-theme.css"), encoding="utf-8") as fh:
        theme = fh.read()
    return ("/* Animal NGO directory for rapid-response.in. Generated by scraper/rrcss.py "
            "from styles.css and rr-theme.css; edit those. */\n" + scope(base) + "\n" + scope(theme) + "\n")


def write(path):
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(build())


if __name__ == "__main__":
    write(sys.argv[1] if len(sys.argv) > 1 else os.path.join("site", "rr.css"))
